  /**
   * 计算四柱的所有神煞
   */
  calculateAllShensha(bazi) {
    const { nianzhu, yuezhu, rizhu, shizhu } = bazi;
    const nianzhi = nianzhu[1]; // 年支

    const shensha = {
      年柱: [],
      月柱: [],
      日柱: [],
      时柱: []
    };

    // 计算年柱神煞
    const nianShensha = this.getTwelveGods(nianzhi, nianzhi);
    if (nianShensha) shensha.年柱.push(nianShensha);

    // 计算月柱神煞
    const yuezhi = yuezhu[1];
    const yueShensha = this.getTwelveGods(nianzhi, yuezhi);
    if (yueShensha) shensha.月柱.push(yueShensha);

    // 计算日柱神煞
    const rizhi = rizhu[1];
    const riShensha = this.getTwelveGods(nianzhi, rizhi);
    if (riShensha) shensha.日柱.push(riShensha);

    // 计算时柱神煞
    const shizhi = shizhu[1];
    const shiShensha = this.getTwelveGods(nianzhi, shizhi);
    if (shiShensha) shensha.时柱.push(shiShensha);

    return shensha;
  },

