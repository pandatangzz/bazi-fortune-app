/**
 * 获取鬼谷子两头钳断语
 * @param {Object} bazi - 八字对象
 * @returns {Object} 断语结果
 */
export function getGuiguziDuanyu(bazi) {
  const yearGanZhi = bazi.year.ganZhi;
  const hourZhi = bazi.hour.zhi;

  // 地支转时辰名称
  const shiMap = {
    '子': '子时', '丑': '丑时', '寅': '寅时', '卯': '卯时',
    '辰': '辰时', '巳': '巳时', '午': '午时', '未': '未时',
    '申': '申时', '酉': '酉时', '戌': '戌时', '亥': '亥时'
  };

  const shiChen = shiMap[hourZhi];

  // 查询断语
  const yearData = GUIGUZI_DUANYU[yearGanZhi];

  if (yearData && yearData[shiChen]) {
    return {
      年柱: yearGanZhi,
      时辰: shiChen,
      ...yearData[shiChen],
      说明: '鬼谷子两头钳以年柱和时辰为主，推断人生命运走向'
    };
  }

  // 如果没有找到具体数据，返回通用断语
  return getGeneralDuanyu(bazi);
}

