/**
 * 获取格局批语
 */
export function getGejuPiyu(geju, rizhuStrength) {
  const gejuName = geju.name.replace('格', '');
  const strength = rizhuStrength === '身旺' ? '身旺' : '身弱';

  if (GEJU_PIYU[gejuName] && GEJU_PIYU[gejuName][strength]) {
    return GEJU_PIYU[gejuName][strength];
  }

  return {
    批语: geju.description,
    出处: '《渊海子平》',
    详解: '此格局需要具体分析，结合整体命局判断。',
    应验: '需要结合大运流年具体分析。',
    注意: '注意喜忌神的配置。'
  };
}

