  /**
   * 根据日柱天干地支计算时柱天干
   * 来源: i.java 的 A() 和 B() 方法
   */
  getShichenTiangan(rizhuTiangan, shichenDizhi) {
    // 时辰地支转索引
    const dizhiIndex = this.dizhi.indexOf(shichenDizhi);
    if (dizhiIndex === -1) return '';

    // 日干转索引
    const tianganIndex = this.tiangan.indexOf(rizhuTiangan);
    if (tianganIndex === -1) return '';

    // 计算时干（五虎遁）
    // 甲己日起甲子时，乙庚日起丙子时，丙辛日起戊子时，丁壬日起庚子时，戊癸日起壬子时
    const wuhuDun = {
      '甲': 1, '己': 1,  // 甲己日从甲开始
      '乙': 3, '庚': 3,  // 乙庚日从丙开始
      '丙': 5, '辛': 5,  // 丙辛日从戊开始
      '丁': 7, '壬': 7,  // 丁壬日从庚开始
      '戊': 9, '癸': 9   // 戊癸日从壬开始
    };

    const startTianganIndex = wuhuDun[rizhuTiangan];
    if (!startTianganIndex) return '';

    // 子时对应的天干索引，然后根据地支推算
    // 地支顺序：子丑寅卯辰巳午未申酉戌亥（1-12）
    const shichenOffset = dizhiIndex - 1; // 子=0, 丑=1, ...
    let resultIndex = (startTianganIndex + shichenOffset) % 10;
    if (resultIndex === 0) resultIndex = 10;

    return this.tiangan[resultIndex];
  },

  /**
   * 计算日柱（从公历日期）
   * 来源: BaziToShengri.java 的 b() 方法
   */
  calculateRizhu(year, month, day) {
    // 计算从基准日期到目标日期的总天数
    let totalDays = 0;

    // 累加年份的天数
    for (let y = 1; y < year; y++) {
      totalDays += 365;
    }

    // 累加月份的天数
    for (let m = 1; m < month; m++) {
      totalDays += this.monthDays[m];
    }

    // 加上当月天数
    totalDays += day;

    // 计算闰年天数
    let leapDays = Math.floor((year - 1) / 4);

    // 减去百年不闰的年份
    for (let y = 100; y < year; y += 100) {
      if (y % 400 !== 0) {
        leapDays--;
      }
    }

    // 如果当年是闰年且已过2月，加1天
    if (((year % 4 === 0 && year % 100 !== 0) || year % 400 === 0) && month >= 3) {
      leapDays++;
    }

    // 总天数加上闰年天数，再加上基准偏移量13
    const jiazi60Index = ((leapDays + totalDays) + 13) % 60;

    return this.jiazi[jiazi60Index === 0 ? 60 : jiazi60Index];
  }
